def start_assessment(career, skills):
    print("===== SkillPath AI Assessment =====")
    print("Answer the questions to check your current skill level.\n")

    score = 0
    skill_results = {}

    career_questions = CAREER_ASSESSMENTS.get(career, {})

    for skill in skills:
        skill_data = career_questions.get(skill)

        if skill_data is None:
            print(f"(No question available yet for {skill} — skipping)")
            continue

        print(f"\n{skill_data['question']}")
        for i, option in enumerate(skill_data["options"], start=1):
            print(f"  {i}. {option}")

        user_choice = input("Enter option number: ").strip()

        if user_choice.isdigit() and 1 <= int(user_choice) <= len(skill_data["options"]):
            selected_option = skill_data["options"][int(user_choice) - 1]
        else:
            selected_option = None

        if selected_option == skill_data["answer"]:
            score += 1
            skill_results[skill] = "Known"
        else:
            skill_results[skill] = "Needs Improvement"

    print("\nAssessment completed!")
    print("Your score:", score, "/", len(skill_results))
    print("\nSkill Analysis:")

    for skill, status in skill_results.items():
        print("-", skill, "→", status)

    return skill_results


def find_skill_gaps(skill_results):
    skill_gaps = []

    for skill, status in skill_results.items():
        if status == "Needs Improvement":
            skill_gaps.append(skill)

    return skill_gaps


if __name__ == "__main__":
    test_career = "Web Development"
    test_skills = ["HTML", "CSS", "JavaScript"]
    results = start_assessment(test_career, test_skills)
    skill_gaps = find_skill_gaps(results)

    print("\nSkill Gaps:")
    for skill in skill_gaps:
        print("-", skill)